def _xcp_if_data(request_id: int, response_id: int, bitrate: int) -> str:
    return "\n".join([
        "    /begin IF_DATA XCP",
        "      /begin PROTOCOL_LAYER 0x0100 2000 2000 0 0 0 0 0 8 8 BYTE_ORDER_MSB_LAST ADDRESS_GRANULARITY_BYTE",
        "      /end PROTOCOL_LAYER",
        f"      /begin XCP_ON_CAN 0x0100 CAN_ID_MASTER 0x{request_id:X} CAN_ID_SLAVE 0x{response_id:X} BAUDRATE {bitrate}",
        "      /end XCP_ON_CAN",
        "    /end IF_DATA",
    ])  # fmt: skip


def create_project(target: Any, board: str, folder: str | Path, request_id: int = 0x7F0,
                   response_id: int = 0x7F1, bitrate: int = 500000) -> Path:  # fmt: skip
    """Write a project for *board* (a key of :data:`BOARDS`) with the generated code of *target* (a model or a
    subsystem). ``io.c`` is kept if it exists. Returns the folder."""
    if board not in BOARDS:
        raise ValueError(f"unknown board {board!r}; choose one of {', '.join(BOARDS)}")
    code = generate_c(target)
    out = Path(folder)
    src = out / "main" if board == "esp32" else out
    src.mkdir(parents=True, exist_ok=True)
    for name, text in code.c_files.items():
        (src / name).write_text(text, encoding="utf-8")
    files = {
        "nervus_xcp.c": XCP_C,
        "nervus_xcp.h": XCP_H,
        "nervus_target.h": TARGET_H,
        "board.c": BOARD_C[board],
        "main.c": _main_c(code, request_id, response_id, bitrate, board == "host"),
    }
    if board == "stm32_nucleo_g474re":
        files["stm32g4xx_hal_conf.h"] = HAL_CONF
    for name, text in files.items():
        (src / name).write_text(text, encoding="utf-8")
    if not (src / "io.c").exists():
        (src / "io.c").write_text(_io_c(code), encoding="utf-8")
    sources = sorted({*(n for n in code.c_files if n.endswith(".c")), "nervus_xcp.c", "board.c", "main.c", "io.c"})
    for name, text in _build_files(board, code, sources).items():
        path = out / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    a2l_name = next((n for n in code.files if n.endswith(".a2l")), None)
    if a2l_name is not None:
        a2l = code.files[a2l_name].replace("  /end MODULE", _xcp_if_data(request_id, response_id, bitrate) +
                                           "\n  /end MODULE", 1)  # fmt: skip
        (out / a2l_name).write_text(a2l, encoding="utf-8")
    if board == "stm32_nucleo_g474re":
        (out / "README.txt").write_text(STM32_README, encoding="utf-8")
    return out


STM32_README = """STM32 Nucleo-G474RE project, generated by Nervus.

1. Install arm-none-eabi-gcc and STM32CubeProgrammer, and download STM32CubeG4 (st.com, or
   git clone https://github.com/STMicroelectronics/STM32CubeG4 --recursive).
2. Copy the linker script STM32G474RETx_FLASH.ld here (from an STM32CubeIDE project for the
   Nucleo-G474RE, or from the STM32CubeG4 examples).
3. make STM32CUBE=/path/to/STM32CubeG4
4. make flash   (the Nucleo's ST-LINK, over the USB cable)
5. Connect a 3.3 V CAN transceiver to PA12 (TX) and PA11 (RX), then measure and calibrate with
   Tools > Calibration > XCP on CAN, with the A2L file of this folder (after step 6).
6. Nervus writes the real addresses into the A2L file after the build: fill_a2l_addresses(folder).
"""


def fill_a2l_addresses(folder: str | Path) -> Path:
    """Write the addresses of the built program (the .elf, .so or ESP-IDF build) into the project's A2L file."""
    from nervus.codegen.a2l import fill_addresses, symbol_addresses

    out = Path(folder)
    binaries = [*out.glob("*.elf"), *out.glob("*.so"), *out.glob("build/*.elf")]
    if not binaries:
        raise FileNotFoundError(f"no built program in {out}; build the project first")
    a2l = next(out.glob("*.a2l"))
    a2l.write_text(fill_addresses(a2l.read_text(encoding="utf-8"), symbol_addresses(binaries[0])), encoding="utf-8")
    return a2l


def missing_tool(board: str) -> str | None:
    """The build tool the board needs that is not installed (None if it is there)."""
    tool = BOARDS[board].tool
    return None if shutil.which(tool) else tool


def build(folder: str | Path, board: str) -> subprocess.CompletedProcess[str]:
    """Build the project with the board's tools (see :data:`BOARDS`)."""
    tool = missing_tool(board)
    if tool is not None:
        raise FileNotFoundError(f"{tool} is not installed (needed to build for {BOARDS[board].name})")
    return subprocess.run(BOARDS[board].build, cwd=folder, capture_output=True, text=True)


def flash(folder: str | Path, board: str) -> subprocess.CompletedProcess[str]:
    """Program the board (connected over USB)."""
    if not BOARDS[board].flash:
        raise ValueError(f"{BOARDS[board].name} is not flashed")
    return subprocess.run(BOARDS[board].flash, cwd=folder, capture_output=True, text=True)
