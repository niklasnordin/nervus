XCP_C = r"""/*
 * nervus_xcp.c: a small XCP-on-CAN slave (ASAM MCD-1 XCP) for measurement and calibration by polling:
 * CONNECT, DISCONNECT, GET_STATUS, SET_MTA, UPLOAD, SHORT_UPLOAD, DOWNLOAD, SHORT_DOWNLOAD.
 * Only the memory of the model's data structs can be read, and only its calibration parameters written.
 * Generated by Nervus; portable C99 without dynamic memory.
 */
#include "nervus_xcp.h"

#define XCP_CONNECT        0xFFu
#define XCP_DISCONNECT     0xFEu
#define XCP_GET_STATUS     0xFDu
#define XCP_SET_MTA        0xF6u
#define XCP_UPLOAD         0xF5u
#define XCP_SHORT_UPLOAD   0xF4u
#define XCP_DOWNLOAD       0xF0u
#define XCP_SHORT_DOWNLOAD 0xEDu
#define XCP_ERR_CMD_UNKNOWN   0x20u
#define XCP_ERR_OUT_OF_RANGE  0x22u
#define XCP_ERR_ACCESS_DENIED 0x24u
#define XCP_ERR_SEQUENCE      0x29u

static uint8_t nv_connected = 0u;
static uintptr_t nv_mta = 0u;
static uintptr_t nv_base = 0u; /* added to protocol addresses (0 on a microcontroller) */

typedef struct { uintptr_t start; uint32_t size; uint8_t writable; } nv_region_t;
static nv_region_t nv_regions[NV_XCP_MAX_REGIONS];
static uint32_t nv_n_regions = 0u;

void nv_xcp_add_region(const void *start, uint32_t size, uint8_t writable)
{
    if (nv_n_regions < NV_XCP_MAX_REGIONS) {
        nv_regions[nv_n_regions].start = (uintptr_t)start;
        nv_regions[nv_n_regions].size = size;
        nv_regions[nv_n_regions].writable = writable;
        nv_n_regions++;
    }
}

void nv_xcp_set_base(uintptr_t base) { nv_base = base; }

static int nv_allowed(uintptr_t addr, uint32_t n, uint8_t write)
{
    uint32_t k;
    for (k = 0u; k < nv_n_regions; k++) {
        const nv_region_t *r = &nv_regions[k];
        if ((addr >= r->start) && ((addr + n) <= (r->start + r->size))) {
            return (write == 0u) || (r->writable != 0u);
        }
    }
    return -1;
}

static uint8_t nv_error(uint8_t *resp, uint8_t code)
{
    resp[0] = 0xFEu;
    resp[1] = code;
    return 2u;
}

static uint32_t nv_address(const uint8_t *p) /* Intel byte order */
{
    return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
}

uint8_t nv_xcp_handle(const uint8_t *req, uint8_t len, uint8_t *resp)
{
    uint8_t n;
    uint8_t k;
    int ok;
    uintptr_t addr;
    if (len == 0u) {
        return 0u;
    }
    if (req[0] == XCP_CONNECT) {
        nv_connected = 1u;
        resp[0] = 0xFFu; resp[1] = 0x01u; resp[2] = 0x00u; resp[3] = 8u; resp[4] = 8u; resp[5] = 0u;
        resp[6] = 1u; resp[7] = 1u;
        return 8u;
    }
    if (nv_connected == 0u) {
        return nv_error(resp, XCP_ERR_SEQUENCE);
    }
    n = (len > 1u) ? req[1] : 0u;
    switch (req[0]) {
    case XCP_DISCONNECT:
        nv_connected = 0u;
        resp[0] = 0xFFu;
        return 1u;
    case XCP_GET_STATUS:
        for (k = 0u; k < 6u; k++) { resp[k] = 0u; }
        resp[0] = 0xFFu;
        return 6u;
    case XCP_SET_MTA:
        if (len < 8u) { return nv_error(resp, XCP_ERR_OUT_OF_RANGE); }
        nv_mta = nv_base + (uintptr_t)nv_address(&req[4]);
        resp[0] = 0xFFu;
        return 1u;
    case XCP_UPLOAD:
    case XCP_SHORT_UPLOAD:
        if (n > 7u) { return nv_error(resp, XCP_ERR_OUT_OF_RANGE); }
        if ((req[0] == XCP_SHORT_UPLOAD) && (len < 8u)) { return nv_error(resp, XCP_ERR_OUT_OF_RANGE); }
        addr = (req[0] == XCP_UPLOAD) ? nv_mta : (nv_base + (uintptr_t)nv_address(&req[4]));
        ok = nv_allowed(addr, n, 0u);
        if (ok < 0) { return nv_error(resp, XCP_ERR_OUT_OF_RANGE); }
        resp[0] = 0xFFu;
        for (k = 0u; k < n; k++) { resp[1u + k] = ((const volatile uint8_t *)addr)[k]; }
        if (req[0] == XCP_UPLOAD) { nv_mta += n; }
        return (uint8_t)(1u + n);
    case XCP_DOWNLOAD:
    case XCP_SHORT_DOWNLOAD:
        if ((req[0] == XCP_DOWNLOAD) ? (n > 6u) : (n > 2u)) { return nv_error(resp, XCP_ERR_OUT_OF_RANGE); }
        addr = (req[0] == XCP_DOWNLOAD) ? nv_mta : (nv_base + (uintptr_t)nv_address(&req[4]));
        ok = nv_allowed(addr, n, 1u);
        if (ok < 0) { return nv_error(resp, XCP_ERR_OUT_OF_RANGE); }
        if (ok == 0) { return nv_error(resp, XCP_ERR_ACCESS_DENIED); }
        for (k = 0u; k < n; k++) { ((volatile uint8_t *)addr)[k] = req[2u + k]; }
        if (req[0] == XCP_DOWNLOAD) { nv_mta += n; }
        resp[0] = 0xFFu;
        return 1u;
    default:
        return nv_error(resp, XCP_ERR_CMD_UNKNOWN);
    }
}
"""

