"""Development boards: the generated code as a complete project for a board with CAN, with an XCP slave.

    from nervus.codegen.boards import BOARDS, create_project
    create_project(model.block("ECU"), "stm32_nucleo_g474re", "build/ecu_board")   # or "esp32", "host"

A project contains the generated code, a main loop that calls the step function at the base period, a small
hardware layer for the board (CAN, a millisecond clock, the inputs and outputs), the portable XCP-on-CAN slave
``nervus_xcp.c`` (so the board can be measured and calibrated from the Calibration window, INCA or CANape), the
A2L file with the board's CAN identifiers, and the build files of the board's own tools:

=====================  ===============================  ============================================
Board                  CAN                              Build and flash
=====================  ===============================  ============================================
``stm32_nucleo_g474re`` FDCAN1 on PA11/PA12 (classic CAN) ``make`` with arm-none-eabi-gcc and STM32CubeG4;
                                                          ``make flash`` (STM32CubeProgrammer)
``esp32``              TWAI on GPIO 5 (TX) / 4 (RX)      ``idf.py build flash`` (ESP-IDF)
``host``               none (CAN frames from a test)      ``make`` with the computer's C compiler
=====================  ===============================  ============================================

Every board needs a CAN transceiver between its CAN pins and the bus (see the Hardware page of the docs). Only
``io.c`` is meant to be edited: it reads the sensors into the model's inputs and drives the actuators from its
outputs. The board layers follow the vendors' published APIs but have not been tested on hardware yet.
"""

