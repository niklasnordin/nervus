def _main_c(code: GeneratedCode, request_id: int, response_id: int, bitrate: int, host: bool) -> str:
    p = code.name
    period_ms = code.base_period * 1000
    loop = [
        "    uint32_t id;",
        "    uint8_t data[8], answer[8], len, n, k;",
        "    while (nv_can_receive(&id, data, &len) != 0) {",
        "        if (id == NV_XCP_REQUEST_ID) { /* XCP from the calibration tool */",
        "            n = nv_xcp_handle(data, len, answer);",
        "            for (k = n; k < 8u; k++) { answer[k] = 0u; }",
        "            if (n > 0u) { (void)nv_can_send(NV_XCP_RESPONSE_ID, answer, 8u); }",
        "        }",
        "    }",
        "    if ((uint32_t)(nv_millis() - nv_next) < 0x80000000u) { /* the base period has passed */",
        "        nv_next += NV_PERIOD_MS;",
        "        nv_read_inputs();",
        f"        {p}_step();",
        "        nv_write_outputs();",
        "    }",
    ]
    lines = [
        "/* main.c: runs the generated code at its base period and answers XCP on CAN. Generated by Nervus. */",
        f'#include "{p}.h"',
        '#include "nervus_target.h"',
        '#include "nervus_xcp.h"',
        "",
        f"#define NV_PERIOD_MS {max(1, round(period_ms))}u /* base period {code.base_period:g} s */",
        f"#define NV_XCP_REQUEST_ID 0x{request_id:X}u",
        f"#define NV_XCP_RESPONSE_ID 0x{response_id:X}u",
        f"#define NV_CAN_BITRATE {bitrate}u",
        "",
        "static uint32_t nv_next;",
        "",
        "void nv_setup(void)",
        "{",
        "    nv_board_init();",
        "    nv_can_init(NV_CAN_BITRATE);",
        f"    {p}_initialize();",
        f"    nv_xcp_add_region(&{p}_P, (uint32_t)sizeof({p}_P), 1u); /* calibration parameters */",
        f"    nv_xcp_add_region(&{p}_B, (uint32_t)sizeof({p}_B), 0u); /* signals */",
        f"    nv_xcp_add_region(&{p}_DW, (uint32_t)sizeof({p}_DW), 0u); /* states */",
        "    nv_next = nv_millis();",
        "}",
        "",
        "void nv_loop(void) /* call it as often as possible */",
        "{",
        *loop,
        "}",
        "",
    ]
    if not host:
        lines += ["#ifdef ESP_PLATFORM", "void app_main(void)", "#else", "int main(void)", "#endif", "{",
                  "    nv_setup();", "    for (;;) {", "        nv_loop();", "    }", "}", ""]  # fmt: skip
    return "\n".join(lines)


def _io_c(code: GeneratedCode) -> str:
    p = code.name
    read = [f"    /* {p}_U.{n}[{k}] = ...; */" for n, w in code.inputs for k in range(w)] or ["    /* no inputs */"]
    write = [f"    /* ... = {p}_Y.{n}[{k}]; */" for n, w in code.outputs for k in range(w)] or ["    /* no outputs */"]
    return "\n".join([
        "/* io.c: the board's sensors and actuators. Edit this file: Nervus does not overwrite it. */",
        f'#include "{p}.h"',
        '#include "nervus_target.h"',
        "",
        "void nv_read_inputs(void) /* before every step: sensors (ADC, CAN, digital inputs) into the inputs */",
        "{",
        *read,
        "}",
        "",
        "void nv_write_outputs(void) /* after every step: the outputs to the actuators (PWM, CAN, digital outputs) */",
        "{",
        *write,
        "}",
        "",
    ])  # fmt: skip


def _build_files(board: str, code: GeneratedCode, sources: list[str]) -> dict[str, str]:
    p = code.name
    if board == "esp32":
        srcs = " ".join(f'"{s}"' for s in sources)
        return {
            "CMakeLists.txt": "cmake_minimum_required(VERSION 3.16)\ninclude($ENV{IDF_PATH}/tools/cmake/project.cmake)\n"
                              f"project({p})\n",
            "main/CMakeLists.txt": f'idf_component_register(SRCS {srcs} INCLUDE_DIRS "." REQUIRES driver esp_timer)\n',
        }  # fmt: skip
